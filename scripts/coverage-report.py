#!/usr/bin/env python3
"""Emit a Markdown coverage report from db/grimoire.db.

Usage:
    python3 scripts/coverage-report.py > COVERAGE.md

The report is generated, never hand-edited. It covers raids, dungeons,
seasonal activities, rotating events, speaker depth and known gaps.
"""
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.environ.get('GRIMOIRE_DB') or os.path.join(ROOT, 'db', 'grimoire.db')


def table(rows, cols):
    out = ['| ' + ' | '.join(cols) + ' |', '|' + '|'.join(['---'] * len(cols)) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(x) for x in r) + ' |')
    return '\n'.join(out)


def main():
    conn = sqlite3.connect(DB)
    acts = conn.execute(
        'SELECT slug,name,activity_type,season_slug,transcripts,lines,vaulted '
        'FROM v_activity_coverage ORDER BY lines DESC').fetchall()
    evs = conn.execute(
        'SELECT slug,name,transcripts,lines,occurrences,vaulted '
        'FROM v_event_coverage ORDER BY lines DESC').fetchall()
    total, dialogue = conn.execute(
        'SELECT COUNT(*), SUM(is_stage_dir=0) FROM transcript_lines').fetchone()
    speakers = conn.execute(
        "SELECT tl.speaker, COUNT(*) AS lines FROM transcript_lines tl "
        "JOIN transcripts t ON t.id=tl.transcript_id "
        "WHERE lower(tl.speaker) IN "
        "('calus','rhulk','nezarec','savathûn','oryx','riven','sjur eido','sedia',"
        "'xivu arath','mara sov','sloane','failsafe','caiatl','rhulk') "
        "AND tl.is_stage_dir=0 AND tl.is_optional=0 "
        "AND COALESCE(t.source_tier,'') != 'game_caption' "
        'GROUP BY tl.speaker ORDER BY lines DESC').fetchall()

    def pick(rows):
        return [(r[0], r[1], r[3], r[4], r[5], r[6]) for r in rows]

    raids = pick([r for r in acts if r[2] == 'raid'])
    dungeons = pick([r for r in acts if r[2] == 'dungeon'])
    seasonal = pick([r for r in acts if r[2] in ('seasonal', 'public_event')])
    gaps = [r[0] for r in acts if r[5] == 0]   # no dialogue lines
    event_gaps = [r[0] for r in evs if r[2] == 0]

    print(f'''# Canon Coverage: Activities, Seasons and Events

Generated by `scripts/coverage-report.py` from `db/grimoire.db`. This is
coverage of spoken dialogue, not lore books, item text or grimoire cards.

Totals: {total:,} transcript rows, {dialogue:,} dialogue lines, {len(acts)}
catalogued activities and {len(evs)} rotating events.

## Discovery

```bash
python3 db/query.py coverage
python3 db/query.py activity menagerie
python3 db/query.py search calus --season 7
python3 db/query.py search shaxx --event "Iron Banner"
```

Four axes, all optional filters: expansion, official numeric season/episode,
activity and event. Confidence is `explicit`, `derived`, `manual` or `unknown`.

## Raids

{table(raids, ['Slug', 'Activity', 'Season', 'Transcripts', 'Lines', 'Vaulted'])}

## Dungeons

{table(dungeons, ['Slug', 'Activity', 'Season', 'Transcripts', 'Lines', 'Vaulted'])}

## Seasonal activities

{table(seasonal, ['Slug', 'Activity', 'Season', 'Transcripts', 'Lines', 'Vaulted'])}

## Rotating events

{table(evs, ['Slug', 'Event', 'Transcripts', 'Lines', 'Occurrences', 'Vaulted'])}

Events repeat across seasons; `event_occurrences` stores one row per year.
Events with no spoken-dialogue source in the archive:
{', '.join('`' + e + '`' for e in event_gaps) if event_gaps else 'none'}.

## Speaker depth

{table(speakers, ['Speaker', 'Lines'])}

## Known gaps

Activities with no dialogue yet:

{', '.join('`' + g + '`' for g in gaps) if gaps else 'none'}

Missing dialogue is reported, never invented. `unknown` classification is a
valid state.

## Ingested sources

- Ishtar Collective: books, cards, transcripts, records, items.
- YouTube captions: cutscenes, corroboration-verified.
- Destinypedia verbatim transcripts: Menagerie (232 Calus lines, including
  Hunter/Titan/Warlock callouts), Last Wish, Vow of the Disciple, Root of
  Nightmares, Deep Stone Crypt, Duality, Leviathan, Shattered Throne, Grasp of
  Avarice, Spire of the Watcher, Ghosts of the Deep, Warlord's Ruin, Vesper's
  Host, Sundered Doctrine, Breach Executable, The Nether, Court of Blades,
  The Coil, Presage, Vox Obscura and Encore.

## Impact on Ghost Shells

A persona sourced from a raid or seasonal figure can pass quote verification
and still be underdetermined as a voice. `source-persona.py` warns below 25
canonical lines and records the count; `finalize-persona.py` repeats the warning.
''')
    conn.close()


if __name__ == '__main__':
    sys.exit(main())
