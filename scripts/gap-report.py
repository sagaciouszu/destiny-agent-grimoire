#!/usr/bin/env python3
"""Emit a Markdown gap ledger from the live database.

Usage:
    python3 scripts/gap-report.py > docs/GAPS.md

Lists activities with no dialogue, event/season gaps, sparse speakers and the
source work that would close each gap.
"""
import os
import sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.environ.get('GRIMOIRE_DB') or os.path.join(ROOT, 'db', 'grimoire.db')


def table(rows, cols):
    out = ['| ' + ' | '.join(cols) + ' |', '|' + '|'.join(['---'] * len(cols)) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(x) for x in r) + ' |')
    return '\n'.join(out)


def main():
    conn = sqlite3.connect(DB)
    zero = conn.execute(
        "SELECT activity_type,slug,name FROM v_activity_coverage "
        'WHERE transcripts=0 ORDER BY activity_type,name').fetchall()
    narration = conn.execute(
        "SELECT activity_type,slug,name,transcripts FROM v_activity_coverage "
        'WHERE transcripts>0 AND lines=0 ORDER BY activity_type,name').fetchall()
    events = conn.execute(
        'SELECT e.slug,e.name,COUNT(DISTINCT c.transcript_id),COUNT(DISTINCT i.item_id) '
        'FROM events e LEFT JOIN transcript_classification c ON c.event_slug=e.slug '
        'LEFT JOIN item_classification i ON i.event_slug=e.slug GROUP BY e.id ORDER BY e.name').fetchall()
    seasons = conn.execute(
        'SELECT season_number,name,transcripts,lines FROM v_season_coverage '
        'WHERE transcripts=0 ORDER BY season_number').fetchall()
    sparse = conn.execute(
        'SELECT speaker,lines FROM v_speakers WHERE lines < 25 ORDER BY lines DESC LIMIT 25').fetchall()
    games = conn.execute(
        "SELECT COALESCE(e.game,'Unclassified') game, COUNT(DISTINCT t.id), "
        "COUNT(tl.id) FROM transcripts t "
        "JOIN transcript_classification c ON c.transcript_id=t.id "
        "LEFT JOIN expansions e ON e.slug=c.expansion_slug "
        "LEFT JOIN transcript_lines tl ON tl.transcript_id=t.id "
        "AND tl.speaker NOT IN ('Narration','Cutscene') "
        'GROUP BY 1 ORDER BY 2 DESC').fetchall()
    print(f'''# Canon Gap Ledger

Generated by `scripts/gap-report.py` from `db/grimoire.db`.

## Coverage by game

{table(games, ['Game', 'Transcripts', 'Dialogue lines'])}

## Activities with no transcript

{table(zero, ['Type', 'Slug', 'Name']) if zero else 'None.'}

## Transcripts with no spoken dialogue

These activities have an encounter transcript, but the source contains only
narration. They are searchable for structure and context; they add no quotes.

{table(narration, ['Type', 'Slug', 'Name', 'Transcripts']) if narration else 'None.'}

## Events

{table(events, ['Event', 'Name', 'Transcripts', 'Items'])}

Events with no spoken transcript are source-limited, not unclassified. Their
items and occurrences are still mapped.

## Seasons with no transcripts

{table(seasons, ['Number', 'Season', 'Transcripts', 'Lines']) if seasons else 'None.'}

Seasons 1-26 have at least one transcript. Seasons 27-28 are catalogued but
source-limited.

## Sparse speakers

{table(sparse, ['Speaker', 'Lines'])}

## Source queue

| Gap | Source that would close it |
|---|---|
| Defiant Battlegrounds, Expedition, Ketchcrash, PsiOps Battlegrounds | Destinypedia pages are stubs; no transcript source found yet |
| Destiny 1 raid dialogue | current encounter transcripts are narration-only; in-raid dialogue is not available |
| Removed seasonal activities (Seasons 12-26) | captioned gameplay compilations, reviewed |
| Sparse raid figures | full encounter transcripts, not intros/cinematics |
| Festival, Dawning, Solstice dialogue | event-specific transcript sources; items already mapped |
| Bungie Day, Moments of Triumph | no spoken transcript source; items and years are mapped |

Never invent dialogue. A gap is reported until a source exists.
''')
    conn.close()


if __name__ == '__main__':
    main()
